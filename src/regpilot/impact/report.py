"""Human-readable outputs of a proposal: data/gate1/<id>/{proposal.json, report.md, impact.csv}."""

import csv
import io
from collections import Counter, defaultdict
from pathlib import Path

from regpilot.impact.models import NOT_COMPLIANT_PROVEN, Proposal, SizeImpact

TIMING_TEXT = {"in_force": "in force now", "new_approvals_only": "new approvals now", "upcoming": "upcoming"}


def effective_verdict(i: SizeImpact) -> str:
    return i.reviewer_verdict or i.verdict


def summarize(impacts: list[SizeImpact]) -> dict:
    c = Counter(effective_verdict(i) for i in impacts)
    unresolved = sum(n for v, n in c.items() if v in NOT_COMPLIANT_PROVEN - {"fail"})
    return {"assessments": len(impacts), "pass": c.get("pass", 0), "fail": c.get("fail", 0),
            "unresolved": unresolved, "not_defined": c.get("not_defined", 0),
            "accepted_risk": c.get("accepted_risk", 0), "by_verdict": dict(sorted(c.items())),
            "sizes_with_fail": sorted({i.size_id for i in impacts if effective_verdict(i) == "fail"})}


def _when(i: SizeImpact) -> str:
    if i.timing == "in_force":
        return "now" + (f" (all approvals since {i.all_from})" if i.all_from else "")
    if i.timing == "new_approvals_only":
        return f"new approvals now; ALL approvals from {i.all_from}" if i.all_from else "new approvals now"
    return f"from {i.new_from or i.all_from}"


def report_md(p: Proposal, status: str = "proposed") -> str:
    s = p.summary
    lines = [
        f"# Impact proposal {p.id}",
        "",
        f"**{p.regulation}** · version {p.celex} (watcher document #{p.document_id}) · as of **{p.as_of}** · "
        f"trigger `{p.trigger}` · status **{status}**",
        "",
        f"| assessments | pass | **fail** | unresolved (not proven compliant) | not defined |",
        f"|---|---|---|---|---|",
        f"| {s['assessments']} | {s['pass']} | **{s['fail']}** | {s['unresolved']} | {s['not_defined']} |",
        "",
        "## Market applicability",
        "",
        *[f"- {a.market}: **{a.status}** ({a.basis})" for a in p.applicability],
    ]
    if p.superseded:
        lines += ["", "Not rated because a later stage replaced them for all approvals as of this date:", "",
                  *[f"- {old.split(':', 1)[1]} → replaced by {new.split(':', 1)[1]}" for old, new in sorted(p.superseded.items())]]
    if p.unassessed_ranges:
        lines += ["", "Not assessed (no market where applicability is established):", "",
                  *[f"- {r['brand']} {r['range_name']} (markets: {', '.join(r['markets']) or 'none'})"
                    for r in p.unassessed_ranges]]

    def table(title: str, rows: list[SizeImpact]):
        if not rows:
            return []
        out = ["", f"## {title} ({len(rows)})", "",
               "| brand / range | size | requirement | when | limit | test | verdict | note |",
               "|---|---|---|---|---|---|---|---|"]
        for i in rows:
            lim = f"{i.comparator} {i.limit:g} {i.unit}" if i.limit is not None else "-"
            test = f"{i.test_value:g} ({i.test_date})" if i.test_value is not None else "-"
            v = effective_verdict(i) + (" (reviewer)" if i.reviewer_verdict else "")
            note = (i.reviewer_reason or i.reason).replace("|", "/")[:90]
            out.append(f"| {i.brand} {i.range_name} | {i.designation} | {i.requirement_id.split(':', 1)[1]} "
                       f"{'🆕' if i.requirement_change == 'added' else ''} | {_when(i)} | {lim} | {test} | {v} | {note} |")
        return out

    order = {"in_force": 0, "new_approvals_only": 1, "upcoming": 2}
    fails = sorted([i for i in p.impacts if effective_verdict(i) == "fail"], key=lambda i: (order[i.timing], i.size_id))
    open_ = [i for i in p.impacts if effective_verdict(i) in NOT_COMPLIANT_PROVEN - {"fail"}]
    lines += table("❌ Fails", fails)
    lines += table("❓ Not proven compliant (needs data or a decision)", open_)

    by_range = defaultdict(Counter)
    for i in p.impacts:
        by_range[f"{i.brand} {i.range_name} [{i.tyre_class}]"][effective_verdict(i)] += 1
    lines += ["", "## By range", "", "| range | pass | fail | other |", "|---|---|---|---|"]
    for r, c in sorted(by_range.items()):
        lines.append(f"| {r} | {c.get('pass', 0)} | {c.get('fail', 0)} | {sum(c.values()) - c.get('pass', 0) - c.get('fail', 0)} |")
    lines += ["", "_Generated by the Reg-Impact agent. A Gate 1 decision by a person is required before use._", ""]
    return "\n".join(lines)


def impact_csv(p: Proposal) -> str:
    buf = io.StringIO()
    fields = ["size_id", "brand", "range_name", "designation", "tyre_class", "markets", "requirement_id", "metric",
              "stage", "timing", "new_from", "all_from", "requirement_change", "comparator", "limit", "unit",
              "test_value", "test_date", "verdict", "margin", "reason", "reviewer_verdict", "reviewer_reason",
              "limit_conditions", "adjustments"]
    w = csv.DictWriter(buf, fieldnames=fields)
    w.writeheader()
    for i in p.impacts:
        d = i.model_dump(mode="json")
        d["markets"], d["limit_conditions"], d["adjustments"] = (" ".join(d["markets"]), " / ".join(d["limit_conditions"]),
                                                                 "; ".join(d["adjustments"]))
        w.writerow({k: d.get(k) for k in fields})
    return buf.getvalue()


def write_artifacts(p: Proposal, root: Path, status: str = "proposed") -> Path:
    folder = root / p.id
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "proposal.json").write_text(p.model_dump_json(indent=1))
    (folder / "report.md").write_text(report_md(p, status))
    (folder / "impact.csv").write_text(impact_csv(p))
    return folder
